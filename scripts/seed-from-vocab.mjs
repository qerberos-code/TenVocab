// Generates supabase/seed.sql from src/vocab.ts + data/word-inventory.json.
// Usage: node scripts/seed-from-vocab.mjs
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, rmSync } from 'node:fs';

const TMP = '.tmp-seed';
rmSync(TMP, { recursive: true, force: true });
execSync(`npx tsc src/vocab.ts --outDir ${TMP} --module es2020 --target es2020 --moduleResolution bundler --skipLibCheck`, { stdio: 'pipe' });
const { VOCAB } = await import(`../${TMP}/vocab.js`);

const inv = JSON.parse(readFileSync('data/word-inventory.json', 'utf8'));
const meta = Object.fromEntries(inv.words.map(r => [r.word, r]));

const q = v => v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const arr = a => `ARRAY[${(a || []).map(q).join(',')}]::text[]`;

const words = VOCAB.map(w => {
  const m = meta[w.id] || {};
  return `(${[q(w.id), q(w.word), q(w.pronunciation), q(w.partOfSpeech), q(w.definition), q(w.example),
    q(w.altDefinition), q(w.altExample), arr(w.synonyms), arr(w.antonyms), q(w.difficulty), w.priority,
    q(w.category), m.tier ?? 'null', arr(m.groups), q(m.source)].join(', ')})`;
});

const items = VOCAB.map(w =>
  `(${[q(w.id), q('context'), q(w.question), arr(w.choices), q(w.answer), q(w.explanation)].join(', ')})`);

const sql = `-- Generated by scripts/seed-from-vocab.mjs — do not edit by hand.
-- ${VOCAB.length} words, ${items.length} authored items.
-- Re-runnable: existing rows are updated, not duplicated.

insert into words (id, word, pronunciation, part_of_speech, definition, example,
  alt_definition, alt_example, synonyms, antonyms, difficulty, priority, category,
  tier, groups, source) values
${words.join(',\n')}
on conflict (id) do update set
  word = excluded.word, pronunciation = excluded.pronunciation,
  part_of_speech = excluded.part_of_speech, definition = excluded.definition,
  example = excluded.example, alt_definition = excluded.alt_definition,
  alt_example = excluded.alt_example, synonyms = excluded.synonyms,
  antonyms = excluded.antonyms, difficulty = excluded.difficulty,
  priority = excluded.priority, category = excluded.category,
  tier = excluded.tier, groups = excluded.groups, source = excluded.source;

-- authored context items; other forms are generated at runtime from the word
delete from items where form = 'context';
insert into items (word_id, form, prompt, choices, answer, explanation) values
${items.join(',\n')};
`;
writeFileSync('supabase/seed.sql', sql);
rmSync(TMP, { recursive: true, force: true });
console.log(`wrote supabase/seed.sql — ${VOCAB.length} words, ${items.length} items`);
